/**
 * Maps JS palette definition to CSS declaration strings.
 */
export function paletteToCssRules(palette) {
  const c = palette.colors;
  return [
    `--bg: ${c.bg};`,
    `--card: ${c.card};`,
    `--card-deep: ${c.cardDeep};`,
    `--line: ${c.line};`,
    `--line-soft: ${c.lineSoft};`,
    `--text: ${c.text};`,
    `--muted: ${c.muted};`,
    `--accent: ${c.accent};`,
    `--accent-text: ${c.accentText};`,
    `--light: ${c.light};`,
    `--light-text: ${c.lightText};`,
    `--gold: ${c.gold};`,
    `--gold-text: ${c.goldText};`,
    `--danger: ${c.danger};`,
    `--teal: ${c.teal};`,
    `--inset: ${c.inset};`,
    `--focus: ${c.focus};`,
    `color-scheme: ${palette.colorScheme};`,
  ];
}
